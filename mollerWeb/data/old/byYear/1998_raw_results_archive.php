  <section class="legacy-shift" id="11oct98hw">
    <h3>11 Oct 1998</h3>
    <p class="legacy-shift-crew">11:00-23:00 The beam energy is 1.720 GeV. The injector angle is</p>
    <p>
    50<sup>o</sup>, the 1/2 wave plate was out. 
           <p> Additional 1/2 wave plate was inserted in the circular polarized beam in order
            to minimize the linear component. Møller "pulser" readout was used in order to read the BCM
            (the x10 output was converted to frequency and counted in the Møller scalers).
           The full information is given
           <a href="../tab/run.tab.3982-4031.ignore">here</a>. A SIN curve was fit to the BCM asymmetries,
           shown on <a href="../plots/half_wave_asym.pdf">a plot</a>, where the full circles
           show the first set of measurements while
           the open circles represent the second set of measurements. 
           It seems that a phase shift happened between these two sets. 
           In the first set of measurements
           the 1/2 wave plate was rotated from 0 to about 340 units (the units turned out to be different
           from degrees). Then it was turned back to 50 units and the result was consistent with the previous ones.
           Then, it was turned to 60 units and a jump happened, 
           perhaps on the source side since
           nothing has been changed in the Hall A setup at this moment.
           It seems also that results are drifting all the time and it is not excluded that the phase would
           change to the opposite after some time.
           The "optimal" for this moment angle of 120 units was left on the device (see the open circles).
           The BCM asymmetry measured at this point was drifting between 0.12 and 0.18%.
           <br>
           NB. The HAPPEX readout/analysis turned on for the last points of the second set 
           provided values for the asymmetries very close to the ours, although
           with the opposite sign.  
           <p>
        </p>
