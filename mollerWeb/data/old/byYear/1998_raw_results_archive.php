    <p>
    Aug 17, 1998. The beam energy is 1.833 GeV. The predicted spin angle 
           at the target is 17<sup>o</sup>. The transverse polarization
           should give a contribution of about 3% of the longitudinal one,
           with a target angle of 35<sup>o</sup>. The polarization was measured 
           with angles of 32<sup>o</sup> (runs 3339-3352)
           and (180-35)<sup>o</sup> (runs 3360-3363). The angles were estimated
           comparing the coincidence rates with a measurement at 90<sup>o</sup>
           (perpendicular target, runs 3355,3357). Averaging the results
           with 32<sup>o</sup> and (180-35)<sup>o</sup> should cancel
           the transverse polarization impact. 
           The polarization obtained is 0.497+/-0.25(stat)+/-1.2(target_angle).
           There is a bias (a false asymmetry?) between the results
           with opposite target polarization. No explanation found so far.
           It might be the beam intensity.
           The full information is given
           <a href="../tab/run.tab.3339-3363">here</a>.
