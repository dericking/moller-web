           <p>
            When the Helmholtz coil flips is sign, it first goes to the highest possible current at the
            given polarity. The measurement at I=0(A) indicates that 
            a considerable residual magnetization exists in the foil, not overcome by this procedure.
            This indicates that the maximum magnetic field does not saturate the foil.
            We can not make any conclusion on the absolute foil polarization. 
           </p>
    
           <p>
            <b>The sign</b> of the vertical beam polarization can be derived taking into account that
            the analyzing power for 90<sup>o</sup> scattering in CM, happening in XZ plane, is: A<sub>ZZ</sub>=-7/9,
            A<sub>XX</sub>=-1/9, A<sub>YY</sub>=+1/9. At positive coil currents the target electron spins
            are polarized along the beam, while in the zig-zagged foil they are looking up.
            Since the measured asymmetry is negative, we conclude that during the 
            period when the helicity signal is at logical 1, the beam spins are pointed down.
           This result is preliminary - we need an access to the hall to make sure that the foil is indeed
           bent the way we think.
           </p>
    
